// Helper to assemble seed quotations with exact engine evaluations
function buildSeedQuotation(
  id: string,
  customer: Customer,
  title: string,
  rawItems: Array<{ product: Product; quantity: number; discountPercent: number }>,
  status: Quotation['status'],
  createdAt: string,
  auditTrail: Quotation['auditTrail'],
  owner: string = 'Marcus Vance',
  priceList: string = 'Standard Commercial 2026',
  deliveryDate: string = '2026-10-15'
): Quotation {
  const evaluatedItems = rawItems.map((r, idx) =>
    evaluateLineItem(
      {
        id: `LI-${id}-${idx + 1}`,
        productId: r.product.id,
        productName: r.product.name,
        category: r.product.category,
        unitPrice: r.product.basePrice,
        quantity: r.quantity,
        discountPercent: r.discountPercent,
      },
      customer.tier
    )
  );

  const evaluation = evaluateQuotationRisk(evaluatedItems, customer.tier);

  return {
    id,
    customerId: customer.id,
    customerName: customer.name,
    customerTier: customer.tier,
    title,
    items: evaluatedItems,
    subtotal: evaluation.subtotal,
    totalDiscountAmount: evaluation.totalDiscountAmount,
    grandTotal: evaluation.grandTotal,
    status,
    riskDiagnosis: evaluation.riskDiagnosis,
    auditTrail,
    createdAt,
    updatedAt: createdAt,
    dealHealthScore: evaluation.dealHealthScore,
    owner,
    priceList,
    deliveryDate,
  };
}

